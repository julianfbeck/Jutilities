import AppKit
import ImageIO
import UniformTypeIdentifiers
import JutilitiesCore

struct ClipboardSourceApplication {
    let name: String
    let bundleIdentifier: String?
}

@MainActor
final class PasteboardMonitor {
    var onCapture: ((ClipboardCapture) -> Void)?
    var onError: ((String) -> Void)?
    var isPaused = false {
        didSet {
            if oldValue != isPaused {
                // Resume starts with the next copy, never a password copied
                // while capture was paused, even between timer ticks.
                observedChangeCount = pasteboard.changeCount
            }
        }
    }
    private let pasteboard: NSPasteboard
    private let frontmostApplication: () -> ClipboardSourceApplication?
    private var timer: Timer?
    private var observedChangeCount: Int
    private let maximumBytes = 60 * 1024 * 1024
    private static let excludedApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.apple.Passwords",
        "com.apple.keychainaccess", "com.bitwarden.desktop", "com.apple.SecurityAgent"
    ]
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "net.antelle.keeweb"
    ]
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    init(pasteboard: NSPasteboard = .general,
         frontmostApplication: @escaping () -> ClipboardSourceApplication? = {
             NSWorkspace.shared.frontmostApplication.map {
                 ClipboardSourceApplication(name: $0.localizedName ?? "Unknown app", bundleIdentifier: $0.bundleIdentifier)
             }
         }) {
        self.pasteboard = pasteboard
        self.frontmostApplication = frontmostApplication
        observedChangeCount = pasteboard.changeCount
    }

    func start() {
        // Only capture new user copies, not the clipboard that predated installation.
        observedChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func stop() { timer?.invalidate(); timer = nil }
    func markOwnWrite() { observedChangeCount = pasteboard.changeCount }

    func poll() {
        let board = pasteboard
        guard board.changeCount != observedChangeCount else { return }
        let generation = board.changeCount
        observedChangeCount = generation
        guard !isPaused else { return }
        let application = frontmostApplication()
        guard !shouldExclude(generation: generation, application: application) else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        // File promises/bookmarks can grant access outside the copied content. Keep the
        // required text/image formats, which can be restored without opening any file.
        let supported: [NSPasteboard.PasteboardType] = [.string, .png, .tiff, .rtf, .html, .URL]
        var representations: [ClipboardRepresentation] = []
        var bytes = 0
        for type in supported where types.contains(type.rawValue) {
            guard let data = board.data(forType: type), !data.isEmpty else { continue }
            guard board.changeCount == generation else { return }
            guard data.count <= maximumBytes - bytes else {
                onError?("This copy is larger than 60 MB and was not added to history.")
                return
            }
            representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
            bytes += data.count
        }
        guard !representations.isEmpty else { return }
        // Decode the captured representations instead of reading the live board again.
        // Promised data can replace the pasteboard while a provider is being called.
        let text = representations.first { $0.type == NSPasteboard.PasteboardType.string.rawValue }
            .flatMap { String(data: $0.data, encoding: .utf8) }
            ?? representations.first { $0.type == NSPasteboard.PasteboardType.URL.rawValue }
                .flatMap { String(data: $0.data, encoding: .utf8) }
        let imageData = representations.first { $0.type == NSPasteboard.PasteboardType.png.rawValue }
            ?? representations.first { $0.type == NSPasteboard.PasteboardType.tiff.rawValue }
        var thumbnail: Data?
        var width: Int?
        var height: Int?
        if let imageData, let source = CGImageSourceCreateWithData(imageData.data as CFData, nil) {
            if let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
                width = properties[kCGImagePropertyPixelWidth] as? Int
                height = properties[kCGImagePropertyPixelHeight] as? Int
            }
            let options: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                            kCGImageSourceThumbnailMaxPixelSize: 96,
                                            kCGImageSourceCreateThumbnailWithTransform: true]
            if let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) {
                thumbnail = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
            }
        }
        let kind: ClipboardKind
        if imageData != nil { kind = .image }
        else if let text, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
                ["http", "https", "mailto"].contains(url.scheme?.lowercased() ?? "") { kind = .link }
        else { kind = .text }
        let title: String
        if kind == .image {
            title = width.flatMap { w in height.map { "Image · \(w) × \($0)" } } ?? "Copied image"
        } else {
            title = String((text ?? "Formatted text").split(whereSeparator: \.isNewline).first.map(String.init)?.prefix(160) ?? "Copied text".prefix(160))
        }
        // A provider can add a sensitive marker without changing clipboard
        // ownership. Check again before any content reaches persistent history.
        guard !shouldExclude(generation: generation, application: application) else { return }
        onCapture?(ClipboardCapture(kind: kind, title: title, text: text,
                                   sourceApp: application?.name ?? "Unknown app",
                                   sourceBundleID: application?.bundleIdentifier,
                                   representations: representations, thumbnail: thumbnail,
                                   imageWidth: width, imageHeight: height))
    }

    private func shouldExclude(generation: Int, application: ClipboardSourceApplication?) -> Bool {
        guard pasteboard.changeCount == generation else { return true }
        guard Set((pasteboard.types ?? []).map(\.rawValue)).isDisjoint(with: Self.ignoredTypes),
              !Self.excludedApps.contains(application?.bundleIdentifier ?? "") else { return true }

        // A background password manager can identify itself even while another
        // app is frontmost. Treat source hints only as an additional exclusion;
        // they never override a sensitive marker or a blocked foreground app.
        for item in pasteboard.pasteboardItems ?? [] where item.types.contains(Self.sourceType) {
            if let source = item.string(forType: Self.sourceType), Self.excludedApps.contains(source) {
                return true
            }
        }
        // Source hints may themselves come from a lazy provider.
        return pasteboard.changeCount != generation
            || !Set((pasteboard.types ?? []).map(\.rawValue)).isDisjoint(with: Self.ignoredTypes)
    }
}
