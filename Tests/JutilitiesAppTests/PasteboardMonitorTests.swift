    @MainActor
    func testResumeDoesNotCaptureAnUnpolledCopyMadeWhilePaused() async throws {
        let board = NSPasteboard(name: NSPasteboard.Name("JutilitiesTests-\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        let monitor = PasteboardMonitor(pasteboard: board, frontmostApplication: { nil })
        var captures: [ClipboardCapture] = []
        monitor.onCapture = { captures.append($0) }

        monitor.isPaused = true
        board.clearContents()
        XCTAssertTrue(board.setString("Synthetic unmarked secret fixture", forType: .string))
        // Resume before the timer polls: paused copies must not be replayed later.
        monitor.isPaused = false
        monitor.poll()
        XCTAssertTrue(captures.isEmpty)

        board.clearContents()
        XCTAssertTrue(board.setString("Ordinary copy after resuming", forType: .string))
        monitor.poll()

        XCTAssertEqual(captures.count, 1)
        XCTAssertEqual(captures.first?.text, "Ordinary copy after resuming")
    }

