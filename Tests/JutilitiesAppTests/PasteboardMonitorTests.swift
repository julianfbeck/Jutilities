    @MainActor
    func testCapturesOrdinarySourceMetadataAndImage() async throws {
        let board = NSPasteboard(name: NSPasteboard.Name("JutilitiesTests-\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        let monitor = PasteboardMonitor(pasteboard: board, frontmostApplication: {
            ClipboardSourceApplication(name: "Fixture image app", bundleIdentifier: "com.example.fixture-image")
        })
        var captures: [ClipboardCapture] = []
        monitor.onCapture = { captures.append($0) }
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2,
                                                  bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                                  isPlanar: false, colorSpaceName: .deviceRGB,
                                                  bytesPerRow: 0, bitsPerPixel: 0))
        for x in 0..<2 {
            for y in 0..<2 {
                // Opaque black/white remains stable when macOS synthesizes TIFF
                // using a different color profile than the original PNG.
                let level = CGFloat((x + y) % 2)
                bitmap.setColor(NSColor(deviceRed: level, green: level, blue: level, alpha: 1), atX: x, y: y)
            }
        }
        let image = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
        let item = NSPasteboardItem()
        XCTAssertTrue(item.setData(image, forType: .png))
        XCTAssertTrue(item.setString("com.example.fixture-image", forType: NSPasteboard.PasteboardType("org.nspasteboard.source")))
        board.clearContents()
        XCTAssertTrue(board.writeObjects([item]))

        monitor.poll()
        monitor.poll()

        let capture = try XCTUnwrap(captures.first)
        XCTAssertEqual(captures.count, 1)
        XCTAssertEqual(capture.kind, .image)
        XCTAssertEqual(capture.imageWidth, 2)
        XCTAssertEqual(capture.imageHeight, 2)
        XCTAssertNotNil(capture.thumbnail)
        XCTAssertEqual(capture.representations.first { $0.type == NSPasteboard.PasteboardType.png.rawValue }?.data,
                       image)
        for representation in capture.representations {
            XCTAssertTrue([NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue]
                .contains(representation.type), "An ordinary image copy must contain only image formats.")
            if representation.type == NSPasteboard.PasteboardType.tiff.rawValue {
                let nativeImage = try XCTUnwrap(NSBitmapImageRep(data: representation.data))
                XCTAssertEqual(nativeImage.pixelsWide, 2)
                XCTAssertEqual(nativeImage.pixelsHigh, 2)
                for x in 0..<2 {
                    for y in 0..<2 {
                        let expected = try XCTUnwrap(bitmap.colorAt(x: x, y: y)?.usingColorSpace(.deviceRGB))
                        let actual = try XCTUnwrap(nativeImage.colorAt(x: x, y: y)?.usingColorSpace(.deviceRGB))
                        XCTAssertEqual(actual.redComponent, expected.redComponent, accuracy: 1 / 255)
                        XCTAssertEqual(actual.greenComponent, expected.greenComponent, accuracy: 1 / 255)
                        XCTAssertEqual(actual.blueComponent, expected.blueComponent, accuracy: 1 / 255)
                        XCTAssertEqual(actual.alphaComponent, expected.alphaComponent, accuracy: 1 / 255)
                    }
                }
            }
        }
    }

    @MainActor
    func testDiscardsCaptureWhenPromisedDataAddsConcealedMarkerWithoutOwnershipChange() async throws {
        let board = NSPasteboard(name: NSPasteboard.Name("JutilitiesTests-\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        let monitor = PasteboardMonitor(pasteboard: board, frontmostApplication: { nil })
        var captures: [ClipboardCapture] = []
        monitor.onCapture = { captures.append($0) }
        let provider = LateConcealedMarkerProvider(board: board)
        let item = NSPasteboardItem()
        XCTAssertTrue(item.setString("Ordinary original fixture", forType: .string))
        XCTAssertTrue(item.setDataProvider(provider, forTypes: [.rtf]))
        board.clearContents()
        XCTAssertTrue(board.writeObjects([item]))
        let generation = board.changeCount

        monitor.poll()

        XCTAssertTrue(provider.wasInvoked, "The marker must arrive during a promised-data read.")
        XCTAssertTrue(provider.markerAddedSuccessfully)
        XCTAssertEqual(board.changeCount, generation, "This regression must retain pasteboard ownership.")
        XCTAssertTrue((board.types ?? []).contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")))
        XCTAssertTrue(captures.isEmpty, "The late privacy marker must discard the original ordinary representation too.")
    }

    @MainActor
    func testDiscardsCaptureWhenPromisedDataReplacesClipboardWithConcealedText() async throws {
        let board = NSPasteboard(name: NSPasteboard.Name("JutilitiesTests-\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        let monitor = PasteboardMonitor(pasteboard: board, frontmostApplication: { nil })
        var captures: [ClipboardCapture] = []
        monitor.onCapture = { captures.append($0) }
        let provider = ConcealedReplacementProvider(board: board)
        let item = NSPasteboardItem()
        XCTAssertTrue(item.setString("Original ordinary content", forType: .string))
        XCTAssertTrue(item.setDataProvider(provider, forTypes: [.rtf]))
        board.clearContents()
        XCTAssertTrue(board.writeObjects([item]))

        monitor.poll()

        XCTAssertTrue(provider.wasInvoked, "The test must exercise a replacement during promised-data capture.")
        XCTAssertTrue(provider.replacementSucceeded)
        XCTAssertTrue(captures.isEmpty, "A changed clipboard generation must discard the entire capture.")

        monitor.poll()
        XCTAssertTrue(captures.isEmpty, "The replacement concealed content must also remain excluded.")
    }
}

private final class LateConcealedMarkerProvider: NSObject, NSPasteboardItemDataProvider {
    private let board: NSPasteboard
    private(set) var wasInvoked = false
    private(set) var markerAddedSuccessfully = false

    init(board: NSPasteboard) {
        self.board = board
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        wasInvoked = true
        item.setData(Data("{\\rtf1 Ordinary original fixture}".utf8), forType: type)
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        // Add a representation without clearContents/declareTypes or a new owner.
        board.addTypes([concealed], owner: nil)
        markerAddedSuccessfully = board.setData(Data(), forType: concealed)
    }
}

private final class ConcealedReplacementProvider: NSObject, NSPasteboardItemDataProvider {
    private let board: NSPasteboard
    private(set) var wasInvoked = false
    private(set) var replacementSucceeded = false

    init(board: NSPasteboard) {
        self.board = board
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        wasInvoked = true
        item.setData(Data("{\\rtf1 Original ordinary content}".utf8), forType: type)
        let replacement = NSPasteboardItem()
        replacement.setString("Synthetic concealed test content", forType: .string)
        replacement.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        board.clearContents()
        replacementSucceeded = board.writeObjects([replacement])
    }
}
